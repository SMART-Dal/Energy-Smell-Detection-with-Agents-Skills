"""RQ2: a table of real repairs, before and after, with what we measured.

Six edits from the dossiers (output/rq2/dossiers/), chosen to show the range:
three strategies that change how the work grows (an index, bisection, slicing
avoided), one that replaces per-character work, one micro-repair that saved
nothing measurable, and one that regressed.

The code lines shown are the key lines of each edit, copied from its diff. The
script checks that every line appears in that edit's diff, so nothing is typed
that the agent did not write. Verdicts and savings are looked up in
output/rq2/edits.csv, and the strategy in analysis/rq2_strategy_coding.csv.

Writes output/rq2/examples.csv and output/rq2/latex/table_rq2_examples.tex, and
copies the table to temp_main_paper/results/generated/.

Run after rq2_repair_dossiers.py:  python3 analysis/rq2_examples.py
"""

import csv
import shutil

from common import OUTPUT_DIR, ROOT, write_csv
from rq2_strategies import read_coding

RQ2 = OUTPUT_DIR / "rq2"
PAPER = ROOT / "temp_main_paper" / "results" / "generated"

# (root cause, edit in edits.csv, key lines before, key lines after)
EXAMPLES = [
    ("C3.S4", "3a",
     ["for news_id in news_ids:", "    hit = find_hit(hits, news_id)"],
     ["for child in hits['root']['children']:",
      "    by_id.setdefault(child['fields']['news_id'], child)",
      "hit = by_id.get(news_id)"]),
    ("C7.S1", "2a",
     ["while len(json.dumps(_bytes2utf8(msg_bytes))) > 8000:", "    msg_bytes = msg_bytes[:-1]"],
     ["while low < high:", "    mid = (low + high + 1) // 2",
      "    if len(json.dumps(_bytes2utf8(msg_bytes[:mid]))) <= 8000:"]),
    ("C10.S1", "4b",
     ["return ''.join((ch for ch in s if unicodedata.category(ch)[0] != 'C'))"],
     ["drop = {ord(ch): None for ch in set(s) if unicodedata.category(ch)[0] == 'C'}",
      "return s.translate(drop) if drop else s"]),
    ("C6.S2", "7a",
     ["pos = string[:pos].rfind(char)"],
     ["pos = string.rfind(char, 0, pos)"]),
    ("C10.S4", "7a",
     ["text = text + '\\n' + line"],
     ["parts.append('\\n')", "parts.append(line)", "data.append((id, header, ''.join(parts)))"]),
    ("C10.S1", "7a",
     ["for f in filters:", "    if f in text:", "        return True", "return False"],
     ["return any((f in text for f in filters))"]),
]


def edit_rows():
    """{(root cause, edit): row of edits.csv}."""
    with open(RQ2 / "edits.csv") as handle:
        return {(r["root_cause"], r["edit"]): r for r in csv.DictReader(handle)}


def diff_of(cause, edit):
    """The text of one edit's section in its dossier."""
    text = (RQ2 / "dossiers" / f"{cause}.md").read_text()
    start = text.index(f"### Edit {edit}:")
    end = text.find("\n### ", start + 1)
    end2 = text.find("\n## ", start + 1)
    ends = [e for e in (end, end2) if e != -1]
    return text[start:min(ends)] if ends else text[start:]


def tex_code(lines):
    """Code lines as LaTeX: typewriter font, special characters escaped, indentation kept."""
    special = {"\\": r"\textbackslash{}", "_": r"\_", "%": r"\%", "&": r"\&", "#": r"\#",
               "$": r"\$", "~": r"\textasciitilde{}", "{": r"\{", "}": r"\}", "^": r"\^{}",
               "'": r"\textquotesingle{}"}
    out = []
    for line in lines:
        indent = len(line) - len(line.lstrip(" "))
        body = "".join(special.get(ch, ch) for ch in line.lstrip(" "))
        out.append(r"\hspace*{" + str(indent * 0.4) + "em}" + body if indent else body)
    return r"\texttt{" + r"\newline ".join(out) + "}"


def main():
    edits = edit_rows()
    coding = read_coding()
    rows = []
    for cause, edit, before, after in EXAMPLES:
        diff = diff_of(cause, edit)
        for line in before + after:                     # every shown line must be in the diff
            if line.strip() not in diff:
                raise SystemExit(f"{cause} {edit}: '{line}' is not in the diff")
        row = edits[(cause, edit)]
        savings = [float(s) for s in row["savings"].split()]
        verdicts = sorted(set(row["verdicts"].split()))
        rows.append({"root_cause": cause, "edit": edit, "repo": row["repo"],
                     "function": row["unit"].split("::")[1], "strategy": coding[(cause, edit)],
                     "verdicts": "/".join(verdicts), "runs": len(savings),
                     "lowest_saving_pct": min(savings), "highest_saving_pct": max(savings),
                     "before": " | ".join(before), "after": " | ".join(after)})
    write_csv(rows, RQ2 / "examples.csv")

    lines = [
        "% Generated by analysis/rq2_examples.py from output/rq2/examples.csv. Do not edit by hand.",
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{RQ2, examples of repairs: the key lines before and after, as the agents wrote them (Python's"
        r" formatting). \textit{Saving}: our verdict and the saving we measured; a range when several runs wrote the"
        r" same edit.}",
        r"\label{tab:rq2-examples}",
        r"\scriptsize",
        r"\begin{tabular}{@{}p{2.6cm}p{6.1cm}p{6.1cm}p{1.6cm}@{}}",
        r"\toprule",
        r"\textbf{Root cause, strategy} & \textbf{Before} & \textbf{After} & \textbf{Saving} \\",
        r"\midrule",
    ]
    for r in rows:
        if r["lowest_saving_pct"] == r["highest_saving_pct"]:
            saving = f"{r['highest_saving_pct']:.1f}\\%"
        else:
            saving = f"{r['lowest_saving_pct']:.1f}--{r['highest_saving_pct']:.1f}\\%"
        name = r["function"].replace("_", r"\_")
        lines.append(f"{r['root_cause']}, {r['strategy'].replace('_', chr(92) + '_')}"
                     f" (\\texttt{{{name}}}) & {tex_code(r['before'].split(' | '))} & "
                     f"{tex_code(r['after'].split(' | '))} & {r['verdicts'].replace('/', ', ')}, {saving} \\\\")
        lines.append(r"\addlinespace")
    lines[-1] = r"\bottomrule"
    lines += [r"\end{tabular}", r"\end{table*}"]
    (RQ2 / "latex").mkdir(parents=True, exist_ok=True)
    (RQ2 / "latex" / "table_rq2_examples.tex").write_text("\n".join(lines) + "\n")
    shutil.copy(RQ2 / "latex" / "table_rq2_examples.tex", PAPER / "table_rq2_examples.tex")
    print("wrote", RQ2 / "examples.csv", "and table_rq2_examples.tex")


if __name__ == "__main__":
    main()
